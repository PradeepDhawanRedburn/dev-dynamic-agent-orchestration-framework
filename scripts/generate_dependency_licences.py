#!/usr/bin/env python3
"""Regenerate docs/governance/dependency-licences.md from the locked environment.

Run from the repository root after `uv sync --locked`:

    uv run --locked python scripts/generate_dependency_licences.py

Licence data comes from each installed package's own metadata (via pip-licenses). It is a
starting point for Legal, not a legal opinion.
"""

import json
import pathlib
import subprocess
import sys
import tomllib
from collections import Counter

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "docs" / "governance" / "dependency-licences.md"
PROJECT = "orchestrator"

# Locked for other platforms, so not installed where this script runs. Read by hand.
NOT_INSTALLED_LICENCES = {
    "httpx2-jsfetch": ("BSD-3-Clause", "PyPI metadata, read 2026-11-21; only used on Emscripten"),
    "colorama": ("BSD License", "PyPI classifier, read 2026-11-21; only used on Windows"),
    "tzdata": ("Apache-2.0", "PyPI metadata, read 2026-11-21; only used on Windows"),
}


def normalise(name: str) -> str:
    return name.lower().replace("_", "-").replace(".", "-")


def licence_of(entry: dict[str, str]) -> str:
    for key in ("License-Expression", "License-Classifier"):
        if entry[key] != "UNKNOWN":
            return entry[key]
    text = entry["License-Metadata"]
    if text == "UNKNOWN":
        return "UNKNOWN"
    # Some packages put the whole licence text in the metadata field; keep the first line.
    return text.strip().splitlines()[0][:80]


def installed() -> list[dict[str, str]]:
    command = [
        sys.executable, "-m", "piplicenses", "-s", "-i", PROJECT,
        "-f", "json", "--from=all", "--with-urls",
    ]  # fmt: skip
    result = subprocess.run(command, check=True, capture_output=True, text=True)
    packages: list[dict[str, str]] = json.loads(result.stdout)
    return packages


def locked() -> dict[str, str]:
    lock = tomllib.loads((ROOT / "uv.lock").read_text(encoding="utf-8"))
    return {normalise(p["name"]): p["version"] for p in lock["package"] if p["name"] != PROJECT}


def main() -> int:
    packages = installed()
    rows = sorted(
        ((p["Name"], p["Version"], licence_of(p), p["URL"]) for p in packages),
        key=lambda row: row[0].lower(),
    )
    present = {normalise(name) for name, *_ in rows}
    missing = {n: v for n, v in locked().items() if n not in present}
    unexplained = sorted(set(missing) - set(NOT_INSTALLED_LICENCES))
    if unexplained:
        print(f"In uv.lock but not installed and not described: {unexplained}", file=sys.stderr)
        return 1

    lines = [
        "# Dependency licences",
        "",
        "Every package resolved in `uv.lock`, with the licence its own metadata declares. For Legal.",
        "Generated by `scripts/generate_dependency_licences.py`; do not edit by hand.",
        "",
        "This is a record of what the packages declare. It is not a legal assessment, and package",
        "metadata can be wrong or incomplete. Regenerate it whenever `uv.lock` changes.",
        "",
        f"Python {sys.version_info.major}.{sys.version_info.minor}, "
        f"{len(rows) + len(missing)} packages, excluding the project itself.",
        "Includes runtime and development dependencies. Packages that exist only on other",
        "platforms are listed in the second table.",
        "",
        "## Summary",
        "",
        "| Licence | Packages |",
        "| --- | --- |",
    ]
    counts = Counter(licence for _, _, licence, _ in rows)
    counts.update(licence for licence, _ in NOT_INSTALLED_LICENCES.values())
    lines += [f"| {licence} | {count} |" for licence, count in sorted(counts.items())]
    lines += ["", "## Packages", "", "| Package | Version | Licence | Home page |", "| --- | --- | --- | --- |"]
    lines += [f"| {name} | {version} | {licence} | {url} |" for name, version, licence, url in rows]
    lines += [
        "",
        "## Locked for other platforms",
        "",
        "| Package | Version | Licence | Source |",
        "| --- | --- | --- | --- |",
    ]
    for name, version in sorted(missing.items()):
        licence, source = NOT_INSTALLED_LICENCES[name]
        lines.append(f"| {name} | {version} | {licence} | {source} |")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}: {len(rows)} installed, {len(missing)} other-platform")
    return 0


if __name__ == "__main__":
    sys.exit(main())
